#!/usr/bin/env python
"""Build the synthetic AMDC corpus.

    python src/build_synthetic_amdc.py                      # SCALE = 0.01
    python src/build_synthetic_amdc.py --scale 1            # full published row counts
    python src/build_synthetic_amdc.py --scale 0.001 --only intra prodcom --no-verify
"""

from __future__ import annotations

import argparse
import shutil
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from amdc_synth import assemble_synthetic_parquets_into_duckdb, report, verify
from amdc_synth.config import OUT, ROOT, Settings
from amdc_synth.pipeline import GENERATORS, run


def _publish(stage: Path, destination: Path) -> None:
    trusted_root = OUT.resolve()
    marker = ".amdc-synth-output"
    if (destination.exists() and destination != trusted_root and
            trusted_root not in destination.parents and
            not (destination / marker).is_file()):
        raise RuntimeError(f"refusing to replace unmarked directory: {destination}")
    (stage / marker).write_text("generated by Synthetic AMDC\n", encoding="utf-8")
    if destination.exists():
        shutil.rmtree(destination)
    stage.replace(destination)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scale", type=float, default=0.01,
                    help="multiplier on every published row count (default 0.01)")
    ap.add_argument("--seed", type=int, default=20260727)
    ap.add_argument("--only", nargs="*", default=[], choices=sorted(GENERATORS),
                    help="build a subset of tables")
    ap.add_argument("--out-dir", type=Path, default=OUT,
                    help="output directory (default: out)")
    ap.add_argument("--no-duckdb", action="store_true")
    ap.add_argument("--no-report", action="store_true")
    ap.add_argument("--no-verify", action="store_true")
    args = ap.parse_args()

    if args.scale <= 0:
        ap.error("--scale must be greater than zero")

    print(
        f"generation scale: {args.scale:g} "
        f"({args.scale:.2%} of published row/firm counts); seed: {args.seed}"
    )

    out_dir = args.out_dir.resolve()
    if out_dir == ROOT or out_dir in ROOT.parents:
        ap.error("--out-dir cannot be the repository root or one of its parents")
    verify.verify_sources()
    out_dir.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=f".{out_dir.name}.build-", dir=out_dir.parent))
    parquet_dir = stage / "parquet"
    report_path = stage / "calibration_report.md"
    duckdb_path = stage / "amdc_synthesized.duckdb"
    cfg = Settings(scale=args.scale, seed=args.seed, out_parquet=parquet_dir)
    t0 = time.time()
    try:
        result = run(cfg, only=tuple(args.only))
        if not args.no_report:
            report.write(cfg, result.tables, result.seconds, path=report_path,
                         parquet_dir=parquet_dir)
        if not args.no_duckdb:
            assemble_synthetic_parquets_into_duckdb.build(
                db_path=duckdb_path, parquet_dir=parquet_dir
            )
        if not args.no_verify:
            if args.only or args.no_report or args.no_duckdb:
                ap.error("--no-verify is required with --only, --no-report, or --no-duckdb")
            checked = verify.verify(stage, cfg)
        _publish(stage, out_dir)
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise

    print(f"parquet -> {out_dir / 'parquet'}")
    for name, n in result.tables.items():
        print(f"  {name:20s} {n:>12,} rows  {result.seconds.get(name, 0):6.1f}s")

    if not args.no_report:
        print(f"report  -> {out_dir / 'calibration_report.md'}")
    if not args.no_duckdb:
        print(f"duckdb  -> {out_dir / 'amdc_synthesized.duckdb'}")
    if not args.no_verify:
        print(f"verify  -> {checked.checks} checks passed")
    print(f"total {time.time() - t0:.1f}s")


if __name__ == "__main__":
    main()
